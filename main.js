/* ==========================================================================
   1. Language & Theme Controllers
   ========================================================================== */

let currentLang = document.documentElement.getAttribute('data-lang') === 'zh' ? 'zh' : 'en';
let currentTheme = document.documentElement.getAttribute('data-theme') === 'light' ? 'light' : 'dark';

function applyLanguage(lang) {
  currentLang = lang === 'zh' ? 'zh' : 'en';
  const dict = I18N[currentLang];

  document.documentElement.setAttribute('data-lang', currentLang);
  document.documentElement.setAttribute('lang', currentLang === 'zh' ? 'zh-CN' : 'en');
  document.title = dict.pageTitle;

  document.querySelectorAll('[data-i18n]').forEach((el) => {
    const key = el.getAttribute('data-i18n');
    if (dict[key] !== undefined) {
      el.textContent = dict[key];
    }
  });

  document.querySelectorAll('[data-i18n-html]').forEach((el) => {
    const key = el.getAttribute('data-i18n-html');
    if (dict[key] !== undefined) {
      el.innerHTML = dict[key];
    }
  });

  document.querySelectorAll('[data-set-lang]').forEach((btn) => {
    btn.classList.toggle('is-active', btn.getAttribute('data-set-lang') === currentLang);
  });

  try {
    localStorage.setItem('lyu-lang', currentLang);
  } catch (_) {}
}

function applyTheme(theme) {
  currentTheme = theme === 'light' ? 'light' : 'dark';
  document.documentElement.setAttribute('data-theme', currentTheme);
  const meta = document.getElementById('meta-theme-color');
  if (meta) {
    meta.setAttribute('content', currentTheme === 'light' ? '#f4f7fc' : '#060911');
  }
  try {
    localStorage.setItem('lyu-theme', currentTheme);
  } catch (_) {}
}

document.querySelectorAll('[data-set-lang]').forEach((btn) => {
  btn.addEventListener('click', () => {
    applyLanguage(btn.getAttribute('data-set-lang'));
  });
});

const themeBtn = document.getElementById('theme-toggle');
if (themeBtn) {
  themeBtn.addEventListener('click', () => {
    applyTheme(currentTheme === 'dark' ? 'light' : 'dark');
  });
}

applyLanguage(currentLang);

